"""Small JSON Schema checker for the CERA agent tool contracts (no extra dependency).

The contracts in ``packages/contracts/agent-tools/agent-tools.v1.json`` are generated by the Main Backend from zod
schemas, so they use a small, known keyword set. This checker supports exactly that set and **refuses** a schema
that uses anything else (``$ref``, ``oneOf``, ``allOf``, ``not`` ...) instead of silently accepting it.
"""

from __future__ import annotations

import re
from typing import Any

SUPPORTED = {
    "type", "properties", "required", "additionalProperties", "items", "anyOf", "enum", "const", "pattern",
    "format", "minLength", "maxLength", "minimum", "maximum", "minItems", "maxItems", "default", "description",
}
_UUID = re.compile(r"^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$")


class SchemaError(ValueError):
    """The schema itself uses an unsupported keyword."""


def errors(schema: dict[str, Any], value: Any, path: str = "$") -> list[str]:
    """All violations as ``path: reason`` strings (empty list = valid). Reasons never echo values."""
    unknown = set(schema) - SUPPORTED
    if unknown:
        raise SchemaError(f"unsupported schema keywords at {path}: {sorted(unknown)}")
    out: list[str] = []
    if "anyOf" in schema:
        if not any(not errors(option, value, path) for option in schema["anyOf"]):
            out.append(f"{path}: matches none of the allowed shapes")
        return out
    if "const" in schema and value != schema["const"]:
        out.append(f"{path}: must be the constant value")
    if "enum" in schema and value not in schema["enum"]:
        out.append(f"{path}: not an allowed value")
    if "type" in schema and not _type_ok(schema["type"], value):
        out.append(f"{path}: wrong type (expected {schema['type']})")
        return out
    if isinstance(value, str):
        if "minLength" in schema and len(value) < schema["minLength"]:
            out.append(f"{path}: too short")
        if "maxLength" in schema and len(value) > schema["maxLength"]:
            out.append(f"{path}: too long")
        if "pattern" in schema and not re.search(schema["pattern"], value):
            out.append(f"{path}: does not match the pattern")
        if schema.get("format") == "uuid" and not _UUID.match(value):
            out.append(f"{path}: not a UUID")
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        if "minimum" in schema and value < schema["minimum"]:
            out.append(f"{path}: below minimum")
        if "maximum" in schema and value > schema["maximum"]:
            out.append(f"{path}: above maximum")
    if isinstance(value, list):
        if "minItems" in schema and len(value) < schema["minItems"]:
            out.append(f"{path}: too few items")
        if "maxItems" in schema and len(value) > schema["maxItems"]:
            out.append(f"{path}: too many items")
        if "items" in schema:
            for i, item in enumerate(value):
                out.extend(errors(schema["items"], item, f"{path}[{i}]"))
    if isinstance(value, dict):
        props: dict[str, Any] = schema.get("properties", {})
        for name in schema.get("required", []):
            if name not in value:
                out.append(f"{path}.{name}: required")
        if schema.get("additionalProperties") is False:
            for name in value:
                if name not in props:
                    out.append(f"{path}.{name}: not allowed")
        for name, sub in props.items():
            if name in value:
                out.extend(errors(sub, value[name], f"{path}.{name}"))
    return out


def _type_ok(expected: str | list[str], value: Any) -> bool:
    kinds = expected if isinstance(expected, list) else [expected]
    return any(_one(k, value) for k in kinds)


def _one(kind: str, value: Any) -> bool:
    if kind == "null":
        return value is None
    if kind == "boolean":
        return isinstance(value, bool)
    if kind == "integer":
        return isinstance(value, int) and not isinstance(value, bool)
    if kind == "number":
        return isinstance(value, (int, float)) and not isinstance(value, bool)
    if kind == "string":
        return isinstance(value, str)
    if kind == "array":
        return isinstance(value, list)
    if kind == "object":
        return isinstance(value, dict)
    raise SchemaError(f"unsupported type {kind!r}")
