"""The eval pipeline's validator port must judge exactly like the real Backend validator (T-099).

``packages/contracts/conformance/extraction-validator.v1.json`` is generated by ``npm run validator-conformance:emit`` in ``back/``
from the TypeScript ``validateAnswers``. If the Backend validator changes, that file is regenerated (the Backend test
fails until then) and this test fails until ``cera_ai/evals/scoring.py backend_checks`` is changed to match.
"""

from __future__ import annotations

import json
from pathlib import Path

from cera_ai.evals.dataset import load_dataset
from cera_ai.evals.scoring import backend_checks

FIXTURE = Path(__file__).resolve().parents[2] / "packages" / "contracts" / "conformance" / "extraction-validator.v1.json"


def _entries() -> list[dict]:
    doc = json.loads(FIXTURE.read_text(encoding="utf-8"))
    assert doc["schema"] == "cera-validator-conformance/1"
    return doc["entries"]


def test_fixture_is_not_trivial() -> None:
    entries = _entries()
    verdicts = [x["passed"] for e in entries for x in e["expected"]]
    assert len(entries) > 300 and True in verdicts and False in verdicts


def test_port_judges_every_conformance_entry_like_the_typescript_validator() -> None:
    cases = {c.case_id: c for c in load_dataset("cera-reply-eval-v1").cases}
    mismatches = []
    for e in _entries():
        if "case_id" in e:
            ask, source = cases[e["case_id"]].ask, cases[e["case_id"]].doc["source_text"]
        else:
            ask, source = e["ask"], e["source_text"]
        answers = [
            {"ask_id": a["ask_id"], "field": a["field"], "value": a["value"], "unit": a["unit"], "evidence": {"quote": a["quote"]}}
            for a in e["answers"]
        ]
        got = [{"passed": r["passed"], "failed": r["failed"]} for r in backend_checks(ask, source, answers, [])]
        if got != e["expected"]:
            mismatches.append((e["id"], e["expected"], got))
    assert not mismatches, f"{len(mismatches)} entries differ, first: {mismatches[0]}"
